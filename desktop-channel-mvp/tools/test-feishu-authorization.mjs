import assert from "node:assert/strict";
import { createDesktopFeishuAuthorization, validFeishuVerificationUrl, feishuMissingScopes } from "../electron/desktop-feishu-authorization.mjs";
import { FEISHU_READ_PERMISSIONS } from "../shared/feishu-authorization-scopes.mjs";
let actor = { key: "synthetic-a", version: 1 };
let clock = 1000;
let resolvePoll;
let calls = [];
let mode = "success";
let connects = 0;
let granted = [FEISHU_READ_PERMISSIONS[0].scope];
let storedOpenId = "";
let available = FEISHU_READ_PERMISSIONS.map(item => item.scope);
const service = createDesktopFeishuAuthorization({ actorContext: () => ({ ...actor }), isExpectedActor: (key, version) => actor.key === key && actor.version === version,
  now: () => clock, qr: async () => "data:image/png;base64,c3ludGhldGlj", connection: { connect: async () => connects++, status: async () => ({ state: mode === "blocked" ? "account_blocked" : "authenticated" }) },
  run: async (args, options = {}) => {
    calls.push(args);
    if (args[0] === "profile") return { value: [{ name: "synthetic" }] };
    if (args[1] === "status") return { value: { verified: true, identities: { user: { verified: true, tokenStatus: "valid", openId: storedOpenId, scope: granted.join(" ") } } } };
    if (args[1] === "check") return { value: { ok: true, granted: args[3].split(" "), missing: null } };
    if (args[1] === "scopes") { if (mode === "inspect_failure") throw new Error("private-error"); return { value: { userScopes: available } }; }
    if (args.includes("--no-wait")) return { value: { verification_url: mode === "url" ? "https://evil.test/?secret=synthetic" : "https://accounts.feishu.cn/synthetic?code=synthetic-url-secret", device_code: "synthetic-private-device", expires_in: 60 } };
    return await new Promise(resolve => { resolvePoll = value => resolve(value); options.signal.addEventListener("abort", () => resolve({ value: { event: "cancelled" } }), { once: true }); });
  },
});
const tick = () => new Promise(resolve => setImmediate(resolve));
assert.equal(validFeishuVerificationUrl("http://accounts.feishu.cn/foo"), false);
assert.equal(validFeishuVerificationUrl("https://accounts.feishu.cn.evil.test/foo"), false);
assert.equal(validFeishuVerificationUrl("https://user:password@accounts.feishu.cn/foo"), false);
let state = await service.request({ action: "inspect" });
assert.equal(state.permissions.items[0].state, "granted");
assert.equal(state.permissions.items[1].state, "needs_authorization");
available = [FEISHU_READ_PERMISSIONS[0].scope];
state = await service.request({ action: "inspect" });
assert.equal(state.permissions.items[1].state, "needs_app_permission");
mode = "inspect_failure";
state = await service.request({ action: "inspect" });
assert.equal(state.permissions.phase, "unavailable");
assert.equal(state.permissions.items.length, 0, "failed lookup cannot assert admin denial");
mode = "success";
assert.equal((await service.request({ action: "begin", permissions: ["raw-command"] })).ok, false);
assert.equal((await service.request({ action: "begin", permissions: ["calendar"], deviceCode: "injected" })).ok, false);
state = await service.request({ action: "begin", permissions: ["calendar"] });
assert.equal(state.phase, "waiting");
assert.equal(JSON.stringify(state).includes("synthetic-private-device"), false);
assert.deepEqual(calls.find(args => args.includes("--no-wait")), ["auth", "login", "--scope", "calendar:calendar.event:read", "--no-wait", "--json"]);
assert.equal((await service.request({ action: "begin", permissions: ["calendar"] })).ok, false, "single poll flow");
resolvePoll({ value: { event: "authorization_complete", missing: ["synthetic-scope"], warning: { type: "missing_scope" }, user_open_id: "synthetic-private-user" }, failed: true });
await tick();
state = await service.request({ action: "status" });
assert.equal(state.phase, "partial", "nonzero completion with missing scopes still validates identity");
assert.equal(connects, 1);
assert.equal(JSON.stringify(state).includes("synthetic-private-user"), false);
assert.equal(state.verificationUrl, "");
mode = "blocked";
await service.request({ action: "begin", permissions: ["calendar"] });
resolvePoll({ value: { event: "authorization_complete", missing: [] } }); await tick();
assert.equal((await service.request({ action: "status" })).phase, "account_blocked");
mode = "success";
await service.request({ action: "begin", permissions: ["calendar"] });
const late = resolvePoll;
await service.request({ action: "cancel" }); late({ value: { event: "authorization_complete", missing: [] } }); await tick();
assert.equal((await service.request({ action: "status" })).phase, "idle");
assert.equal(connects, 2);
await service.request({ action: "begin", permissions: ["calendar"] });
actor = { key: "synthetic-b", version: 2 }; service.clear();
resolvePoll({ value: { event: "authorization_complete", missing: [] } }); await tick();
assert.equal((await service.request({ action: "status" })).phase, "idle");
assert.equal(connects, 2, "old actor cannot attach credentials after cancellation");
await service.request({ action: "begin", permissions: ["calendar"] });
clock += 61_000;
state = await service.request({ action: "status" });
assert.equal(state.phase, "expired"); assert.equal(state.qrImage, "");
state = await service.request({ action: "begin", permissions: ["calendar"] });
assert.equal(state.phase, "waiting", "refresh requests a new device authorization");
await service.request({ action: "cancel" });
storedOpenId = "synthetic-account";
mode = "blocked";
assert.equal((await service.request({ action: "begin", permissions: ["calendar"] })).phase, "existing_login_unverified");
mode = "success";
granted = [FEISHU_READ_PERMISSIONS[0].scope, "bitable:app"];
calls = [];
state = await service.request({ action: "begin", permissions: ["calendar"] });
assert.equal(state.retainedScopeCount, 2);
assert.equal(calls.find(args => args.includes("--no-wait"))[3], "calendar:calendar.event:read bitable:app");
await service.request({ action: "cancel" });
mode = "url";
assert.equal((await service.request({ action: "begin", permissions: ["calendar"] })).phase, "failed");
service.clear();
console.log("Feishu authorization: fixed scopes, missing/admin distinction, cancellation, actor fences, expiry, privacy passed");

assert.deepEqual(feishuMissingScopes({value:{ok:true,granted:["synthetic-read"],missing:null},failed:false},["synthetic-read"]), []);
assert.equal(feishuMissingScopes({value:{ok:true,granted:[],missing:null},failed:false},["synthetic-read"]), null);
assert.equal(feishuMissingScopes({value:{ok:true,granted:["synthetic-read"],missing:null},failed:true},["synthetic-read"]), null);

assert.equal(feishuMissingScopes({value:{ok:false,granted:[],missing:[]},failed:false},["synthetic-read"]), null);
assert.equal(feishuMissingScopes({value:{ok:true,granted:[],missing:[]},failed:false},["synthetic-read"]), null);
assert.equal(feishuMissingScopes({value:{ok:false,granted:[],missing:["unexpected"]},failed:true},["synthetic-read"]), null);

// A mailbox capability needs all four vendor scopes, never only the umbrella.
mode = "success"; actor = { key: "synthetic-mail", version: 9 };
await service.request({ action: "cancel" });
const mail = FEISHU_READ_PERMISSIONS.find(item => item.id === "mail");
available = FEISHU_READ_PERMISSIONS.flatMap(item => item.scopes || [item.scope]);
granted = [mail.scope];
state = await service.request({ action: "inspect" });
assert.equal(state.permissions.items.find(item => item.id === "mail").state, "needs_authorization");
granted = [...mail.scopes];
state = await service.request({ action: "inspect" });
assert.equal(state.permissions.items.find(item => item.id === "mail").state, "granted");
calls = []; granted = [FEISHU_READ_PERMISSIONS[0].scope];
await service.request({ action: "begin", permissions: ["mail"] });
const login = calls.find(args => args.includes("--no-wait"));
assert.deepEqual(new Set(login[login.indexOf("--scope") + 1].split(" ")), new Set([...granted, ...mail.scopes]));
await service.request({ action: "cancel" });
console.log("Composite mailbox scopes require complete grants and preserve existing calendar grants");
