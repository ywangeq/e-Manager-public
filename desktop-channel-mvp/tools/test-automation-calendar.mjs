import assert from 'node:assert/strict';
import {automationSourceTask,automationTaskTitle,automationWeek,calendarWeek,nextAutomationTime,upcomingAutomations,sortedAutomations,automationNextLabel,automationRunSummary} from '../src/lib/automationCalendar.js';
process.env.TZ='Asia/Shanghai';
const now=Date.parse('2026-09-29T02:30:00Z');
const rule={automationId:'hourly',state:'active',startAt:'2026-09-29T01:00:00Z',expiresAt:'2026-09-30T01:00:00Z',intervalSeconds:3600,runCount:1,maxRuns:4};
assert.equal(nextAutomationTime(rule,now),Date.parse('2026-09-29T03:00:00Z'));
assert.equal(nextAutomationTime({...rule,state:'paused'},now),null);
assert.equal(nextAutomationTime({...rule,runCount:4},now),null);
assert.equal(nextAutomationTime({...rule,expiresAt:'2026-09-29T03:00:00Z'},now),null,'expiry is exclusive');
assert.equal(nextAutomationTime({...rule,intervalSeconds:NaN},now),null);
const days=calendarWeek(new Date(now));
assert.equal(days[0].date.getDay(),1);
assert.equal(days[6].date.getDay(),0);
const view=automationWeek([rule],days,now);
assert.equal(view.flatMap(day=>day.events).reduce((n,e)=>n+e.count,0),3,'respect remaining run limit');
assert.equal(view[0].events.length,0,'never invent past execution');
const frequent={...rule,intervalSeconds:60,maxRuns:1000,runCount:0};
const dense=automationWeek([frequent],days,now);
assert.ok(dense.flatMap(day=>day.events).length<=7,'one compact entry per rule/day');
assert.equal(dense.flatMap(day=>day.events).reduce((n,e)=>n+e.count,0),1000);
assert.equal(upcomingAutomations([{...rule,state:'disabled'},rule],now).length,1);
assert.equal(automationWeek([rule],calendarWeek(new Date(now),1),now).flatMap(d=>d.events).length,0);
const titled = {...rule, sourceTaskId:'source-a', employeeId:'employee-a'};
const tasks = [{id:'unrelated',employeeId:'employee-a',taskTitle:'Other task'}, {id:'source-a',employeeId:'employee-a',taskTitle:'  Daily report  ',employeeName:'Report assistant'}];
assert.equal(automationTaskTitle(titled,tasks),'Daily report');
assert.equal(automationSourceTask(titled,tasks).id,'source-a');
assert.equal(automationTaskTitle(titled,[tasks[0]]),'任务名称暂不可用','do not use another task from the same employee');
assert.equal(automationTaskTitle(titled,[{...tasks[1],employeeId:'employee-b'}]),'任务名称暂不可用','employee must match the source reference');
assert.equal(automationTaskTitle({...titled,sourceTaskId:''},tasks),'任务名称暂不可用');
assert.equal(automationTaskTitle(titled,[{...tasks[1],taskTitle:''}]),'任务名称暂不可用');
const later = {...rule, automationId:'later', startAt:'2026-09-29T03:30:00Z'};
assert.deepEqual(automationWeek([later,rule],days,now)[1].events.map(event=>event.rule.automationId),['hourly','later'],'sort by first occurrence, not API order');
process.env.TZ='America/New_York';
const dst=calendarWeek(new Date('2026-11-01T12:00:00Z'));
assert.equal(dst[6].end-dst[6].start,25*3600000,'calendar uses local day boundaries through DST');
console.log('automation calendar boundaries, estimated recurrence, limits and DST passed');

const soon={...rule,automationId:'soon',startAt:new Date(now+60000).toISOString()};
const sortedLater={...rule,automationId:'later',startAt:new Date(now+120000).toISOString()};
const paused={...rule,automationId:'paused',state:'paused'};
const unsorted=[paused,sortedLater,soon];
assert.deepEqual(sortedAutomations(unsorted,now).map(r=>r.automationId),['soon','later','paused']);
assert.deepEqual(unsorted.map(r=>r.automationId),['paused','later','soon'],'sorting does not mutate source state');
assert.match(automationNextLabel(paused,now),/已暂停/);
assert.match(automationNextLabel(soon,now),/下次预计/);
console.log('automation upcoming order and inactive labels passed');

process.env.TZ='Asia/Shanghai';
const historyNow=Date.parse('2026-10-09T04:00:00Z');
const ended={...rule,automationId:'ended',state:'exhausted',runCount:4};
const stored={ended:[{taskId:'ok',scheduledFor:'2026-10-08T00:00:00Z',status:'completed'},{taskId:'bad',scheduledFor:'2026-10-08T01:00:00Z',status:'failed'},{taskId:'ok',scheduledFor:'2026-10-08T00:00:00Z',status:'completed'},{taskId:'invalid',scheduledFor:'invalid',status:'completed'}]};
let past=automationWeek([ended],calendarWeek(new Date(historyNow)),historyNow,stored)[3].events;
assert.equal(past.length,1,'ended rule retains historical day');
assert.equal(past[0].kind,'history');assert.equal(past[0].count,2,'deduplicate task identity and exclude invalid timestamps');
assert.equal(automationRunSummary(past[0].runs),'已完成 1 次 · 失败 1 次');
assert.equal(automationWeek([{...ended,state:'disabled'}],calendarWeek(new Date(historyNow)),historyNow,stored)[3].events.length,1,'disabled rule retains history');
assert.equal(automationWeek([],calendarWeek(new Date(historyNow)),historyNow,stored).flatMap(d=>d.events).length,0,'removed or out-of-scope rule cannot expose cached history');
assert.equal(automationWeek([ended],calendarWeek(new Date(historyNow),-2),historyNow,stored).flatMap(d=>d.events).length,0,'no invented missed or skipped runs');
const boundary={ended:[{taskId:'before',scheduledFor:'2026-10-08T15:59:59Z',status:'completed'},{taskId:'after',scheduledFor:'2026-10-08T16:00:00Z',status:'running'},{taskId:'future',scheduledFor:'2026-10-09T05:00:00Z',status:'completed'}]};
const week=automationWeek([ended],calendarWeek(new Date(historyNow)),historyNow,boundary);
assert.equal(week[3].events[0].count,1);assert.equal(week[4].events[0].count,1,'respect local midnight and never show a future run as history');
console.log('Calendar persisted run history, inactive rules, deduplication, scope and local date boundaries passed');
